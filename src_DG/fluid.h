// ============================================================================
// 间断伽辽金（DG）参数
//
// 使用张量积 Legendre 基函数：φ_m(ξ,η) = L_{px}(ξ) · L_{py}(η)
//   模式编号 m = px*(DG_P+1) + py，其中 px,py ∈ [0, DG_P]
//   参考单元 [-1,1]²  →  物理单元 [x_c±h/2] × [y_c±h/2]
//
// DG_P=1 → 4 个模式（二阶精度）
// DG_P=2 → 9 个模式（三阶精度，默认）
// DG_P=3 → 16 个模式（四阶精度）
// ============================================================================
static constexpr int DG_P  = 1;
static constexpr int DG_NM = (DG_P + 1) * (DG_P + 1);

// ============================================================================
// 网格类
// ============================================================================
class Mesh
{
public:
    // -----------------------------------------------------------------------
    // 网格参数
    // -----------------------------------------------------------------------
    int    nx;       ///< x 方向格子数（含 ghost）
    int    ny;       ///< y 方向格子数
    double da;       ///< 均匀格子尺寸（dx = dy = da）
    double gamma;    ///< 比热比

    // -----------------------------------------------------------------------
    // 原始变量（始终保持与 DG 模式 0 同步）
    // -----------------------------------------------------------------------
    MatrixXd rho;    ///< 密度
    MatrixXd u;      ///< x 方向速度
    MatrixXd v;      ///< y 方向速度
    MatrixXd p;      ///< 压力

    // -----------------------------------------------------------------------
    // 守恒变量单元平均值（= dof[c][0]，保留以兼容 I/O 和后处理代码）
    // U = [rho, rho*u, rho*v, E]^T
    // -----------------------------------------------------------------------
    MatrixXd U0;     ///< 密度          rho
    MatrixXd U1;     ///< x 动量        rho*u
    MatrixXd U2;     ///< y 动量        rho*v
    MatrixXd U3;     ///< 总能量        E

    // -----------------------------------------------------------------------
    // DG 自由度（模态系数）
    //
    //   dof[c][m](i,j)  = 变量 c 在单元 (i,j) 中第 m 个 Legendre 模式系数
    //   c : 0=rho, 1=rho*u, 2=rho*v, 3=E
    //   m : 0..DG_NM-1
    //
    //   不变量：dof[c][0] == U{c}（模式 0 是单元平均值）
    //
    //   正交性：∫∫ φ_m φ_k dξ dη = δ_mk / ((2px+1)(2py+1))
    //   → 质量矩阵对角：M_mm = (h/2)² / ((2px+1)(2py+1))
    // -----------------------------------------------------------------------
    vector<MatrixXd> dof[4];   ///< dof[变量][模式]，每个为 ny×nx 矩阵

    // -----------------------------------------------------------------------
    // 边界类型标记矩阵
    //   0  : 内部流体单元（参与计算）
    //  -1  : 固壁 ghost cell（镜像复制）
    //  -3  : MPI 进程间 ghost cell（通信填充）
    // -----------------------------------------------------------------------
    MatrixXi bctype;

    // -----------------------------------------------------------------------
    // 构造函数
    // -----------------------------------------------------------------------
    Mesh(int n_y, int n_x, double da_, double gamma_);
    explicit Mesh(const std::string& folderPath);

    // -----------------------------------------------------------------------
    // 初始化 DG 自由度（从当前单元平均值 U0-U3 出发，高阶模式置零）
    // 说明：DG 从分段常数初始条件出发是标准做法；高阶模式靠时间推进建立
    // -----------------------------------------------------------------------
    void initDGModes();

    // -----------------------------------------------------------------------
    // 将模式 0 同步回 U0-U3（供 I/O 和后处理使用）
    // -----------------------------------------------------------------------
    void syncCellAverages();
};

// ============================================================================
// 网格分割（MPI 域分解）
// ============================================================================
vector<Mesh> splitMeshVertically(const Mesh& original, int n);

// ============================================================================
// MPI 通信：交换所有 DG 模式的 ghost 列（批量打包，降低通信次数）
// ============================================================================
void exchangeColumns(MatrixXd& matrix, int rank, int num_procs);

/// @brief 一次性交换 4 个变量 × DG_NM 个模式的 ghost 列数据
void exchangeConservativeColumns(Mesh& mesh, int rank, int num_procs);
double phi2(int m, double xi, double eta) noexcept;
// ============================================================================
// DG 核心求解器
// ============================================================================

/// @brief DG 空间离散算子 L(U)，计算各模式系数的时间导数
///
/// 弱形式（对每个测试函数 φ_k 积分后按质量矩阵归一化）：
///
///   M_k * dû_k/dt = ∫∫ [F ∂φ_k/∂ξ + G ∂φ_k/∂η] dξ dη    （体积分）
///                 - ∮ F*·n φ_k dγ                          （面积分，HLLC 通量）
///
/// 输出 dU[c][m] = dû_m^c/dt，形状与 mesh.dof[c][m] 相同
void computeRHS(Mesh& mesh, double dt,
                vector<MatrixXd> dU[4]);

/// @brief TVD限制器（适用于 DG P=1/2）
///
/// 算法：
///   1. 对 x/y 方向线性模式 û_{1,0}, û_{0,1} 施加 minmod 条件
///   2. 若发生限制，将 px+py>1 的高阶模式置零（退化为线性重构）
///
/// 目的：在激波/间断附近消除非物理振荡（Gibbs 现象）
void applyLimiter(Mesh& mesh);

// ============================================================================
// 时间推进（SSP-RK3）
// ============================================================================

/// @brief 三阶强稳定 Runge-Kutta（Shu-Osher 格式）
///
///   Stage 1: U*       = U^n  + dt·L(U^n)
///   Stage 2: U**      = 3/4·U^n + 1/4·(U* + dt·L(U*))
///   Stage 3: U^{n+1}  = 1/3·U^n + 2/3·(U** + dt·L(U**))
///
///   每个阶段之后：施加限制器 → MPI ghost 交换
void updateMesh(Mesh& mesh, double dt, int rank, int num_procs);

// ============================================================================
// HLLC 黎曼求解器（在 DG 面积分中用于计算数值通量）
// ============================================================================

/// @brief HLLC 数值通量（x 方向，法向速度 = U1/U0）
/// @note y 方向：调用前交换 U1↔U2，调用后交换 F1↔F2
void hllcFlux(
    double UL0, double UL1, double UL2, double UL3,
    double UR0, double UR1, double UR2, double UR3,
    double gamma,
    double& F0, double& F1, double& F2, double& F3);

// ============================================================================
// MUSCL 重构（保留以备使用，DG 主循环不调用）
// ============================================================================
void muscl_reconstruct(
    double UL2, double UL1, double UR1, double UR2,
    int limiter,
    double& UL, double& UR);

// ============================================================================
// 后处理
// ============================================================================
void recoverPrimitives(Mesh& mesh);
double computeMaxSpeed(const Mesh& mesh, double gamma);
double recoverAndMaxSpeed(Mesh& mesh);

void saveMeshData(
    const Mesh& mesh,
    int rank,
    const std::string& timestep_folder);

